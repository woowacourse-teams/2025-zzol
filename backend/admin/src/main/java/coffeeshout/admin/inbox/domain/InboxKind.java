package coffeeshout.admin.inbox.domain;

/**
 * 작업함 한 줄의 출처.
 *
 * <p>화면이 이 값으로 칩 색과 이동할 곳을 정한다. 종류를 더 늘리기 전에 물을 것이 하나
 * 있다. <b>그 줄을 보고 운영자가 지금 할 수 있는 일이 있는가.</b> 없으면 작업함이 아니라
 * 알림이고, 알림은 쌓이면 아무도 안 본다.
 */
public enum InboxKind {
    /** 접수된 신고. 읽고 처리 완료로 넘긴다. */
    REPORT,
    /** AI 가 걸러냈거나 판단하지 못한 닉네임. 허용하거나 차단한다. */
    NICKNAME,
    /** 발행에 실패해 격리된 메시지. 원인을 고쳤다면 다시 넣고 아니면 폐기한다. */
    DEAD_LETTER,
}
